def get_palette_by_index(index: int) -> dict | None:
    """Получить палитру по номеру (1-based)."""
    if 1 <= index <= len(PALETTES):
        return PALETTES[index - 1]
    return None


def get_all_palette_names() -> list[str]:
    """Список всех названий палитр."""
    return [p["name"] for p in PALETTES]


def get_palette_count() -> int:
    """Количество палитр."""
    return len(PALETTES)